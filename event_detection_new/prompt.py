DETAILED_SUMMARY_PROMPT = """\
你正在为老人安全 Agent 编写可追溯的中期人物行为记忆。第 {chunk_index} 个片段覆盖相对时间 {frame_range}；原始帧随后会被删除，因此要保留未来解释异常事件所需的前序行为。

【时间规则】
- `N seconds` 只用于确定帧和动作的先后顺序，不需要据此计算真实间隔。
- “本地采集时间”表示动作发生的真实时刻。记录关键行为时优先写本地时间，同时可附相对时间用于定位。
- 必须按 `N seconds` 从小到大整理；即使本地时间异常，也不得改变顺序。

【记录重点：以人为核心，而不只是报警事件】
- 老人做了什么：进食、喝水、服药、拿取或放下物品、起身、坐下、躺下、行走、如厕、休息、睡眠、离床、进出房间、与他人互动等。
- 行为涉及的物品和位置：例如杯子、碗、食物、药盒，以及餐桌、床、沙发、走廊等；看不清具体种类时写“疑似”或“无法确认”，禁止猜测。
- 人物状态变化及顺序：例如“进食→离开餐桌→坐到沙发→按压腹部”。持续无变化的状态只记录一次。
- 异常或求助行为：wave/chest_pain/head_pain/abdomen_pain/rub_shoulder/ok/thumbs_up/fall。
- 异常发生前已经观察到的相关行为必须保留，但只能陈述时间先后，不得擅自建立因果关系。

【输出格式】
- 输出 1-5 条按时间排列的简短记录{length_instruction}，每条格式为：`本地时间（相对时间）：人物行为/状态`。
- 合并连续重复画面；没有明显新行为时，用一条记录说明人物持续所在位置和状态。
- 不确定时明确使用“疑似”“可能”或“无法确认”。仅输出记录，不输出分析过程。

【忽略】
- 衣着、外貌、年龄和性别描述。
- 与人物行为和安全无关的装修、家具等背景细节。
- 轻微镜头晃动及无法支持后续判断的琐碎动作。"""

