DETAILED_SUMMARY_PROMPT = """\
你正在为事件检测系统编写中期记忆。第 {chunk_index} 个片段的关键帧覆盖时间范围 {frame_range}，这些帧之后不再可用，你需要保留下游模型判断事件模式所需的关键信息。

【输出格式】
- 1-3 句话{length_instruction}。无事件时一句话即可；有事件时简要记录。
- 不确定时用"疑似"标注，不要猜测。

【需记录的内容】
- 本片段内出现了哪些事件（wave/chest_pain/head_pain/abdomen_pain/mouth_open/eye_rub/fall/indoor_smoking/smoke_fire/fighting/lying_on_ground/bed_fall/cane_drop/unsteady_gait），分别大约几次
- 是否有持续性的重复事件（如连续挥手超过 5 秒）
- 场景中是否有人出现或离开

【不需要记录的内容】
- 人物的衣着、外貌、年龄、性别
- 背景环境细节（墙壁、家具、光线等）
- 镜头是否轻微晃动

仅输出记录文本。"""

